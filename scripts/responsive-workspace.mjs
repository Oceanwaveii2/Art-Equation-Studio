import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1920, height: 900 } })
  await page.goto(process.env.UI_TEST_BASE_URL || 'http://127.0.0.1:5173/?catalog=demo')
  await page.getByRole('button', { name: 'Split', exact: true }).click()
  const workbench = page.locator('.workbench')
  await workbench.waitFor()
  assert.equal(await workbench.evaluate((el) => el.classList.contains('compact-split')), false)
  const body = page.locator('.app-body')
  const navigatorWidth = await page.locator('.navigator').evaluate((el) => el.getBoundingClientRect().width)
  await page.getByTestId('navigator-panel-handle').focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.locator('.navigator').evaluate((el) => el.getBoundingClientRect().width) > navigatorWidth, true)
  await page.getByTestId('navigator-panel-handle').click()
  await page.getByTestId('inspector-panel-handle').click()
  assert.equal(await body.evaluate((el) => el.classList.contains('navigator-hidden') && el.classList.contains('inspector-hidden')), true)
  assert.equal(await page.locator('.project-center').evaluate((el) => Math.abs(el.getBoundingClientRect().left) < 2), true)
  await page.getByRole('button', { name: 'Show the projects panel' }).click()
  await page.getByRole('button', { name: 'Show the inspector panel' }).click()
  assert.equal(await body.evaluate((el) => !el.classList.contains('navigator-hidden') && !el.classList.contains('inspector-hidden')), true)
  await page.getByRole('button', { name: 'Hide project board strip' }).first().click()
  assert.equal(await page.locator('.project-center.board-strip-hidden').count(), 1)
  // In Split mode the restore affordance is intentionally not shown; switch
  // to Document mode, restore the strip there, then return to Split.
  await page.getByRole('button', { name: 'Document', exact: true }).click()
  await page.getByRole('button', { name: 'Show project boards' }).click()
  assert.equal(await page.locator('.project-board-strip').count(), 1)
  await page.getByRole('button', { name: 'Split', exact: true }).click()
  await page.getByRole('button', { name: 'Hide canvas tool rail' }).click()
  assert.equal(await page.locator('.canvas-tool-rail').count(), 0)
  await page.getByRole('button', { name: 'Show canvas tool rail' }).click()
  await page.locator('.canvas-tool-rail').waitFor()
  assert.equal(await page.locator('.canvas-tool-rail').count(), 1)

  await page.setViewportSize({ width: 1100, height: 800 })
  await page.waitForFunction(() => document.querySelector('.workbench')?.classList.contains('compact-split'))
  assert.equal(await page.locator('.compact-split-tabs button').count(), 2)
  await page.locator('.compact-split-tabs').getByRole('button', { name: 'Document' }).click()
  assert.equal(await page.locator('.document-pane').evaluate((el) => getComputedStyle(el).visibility), 'visible')
  await page.locator('.compact-split-tabs').getByRole('button', { name: 'Canvas' }).click()
  assert.equal(await page.locator('.canvas-pane').evaluate((el) => getComputedStyle(el).visibility), 'visible')
  assert.equal(await page.locator('.document-pane').evaluate((el) => getComputedStyle(el).visibility), 'hidden')
  assert.equal(await page.getByRole('button', { name: /Inspector/i }).count() > 0, true)
  await page.getByRole('button', { name: 'Toggle project inspector' }).click()
  await page.locator('.project-inspector.drawer-open').waitFor({ state: 'visible' })
  assert.equal(await page.locator('.project-inspector.drawer-open').isVisible(), true)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.project-inspector.drawer-open').count(), 0)
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Toggle project inspector')

  await page.setViewportSize({ width: 800, height: 700 })
  await page.waitForTimeout(100)
  assert.equal(await page.getByRole('button', { name: /^Undo the last/ }).isVisible(), true)
  assert.equal(await page.getByRole('button', { name: /^Redo the last/ }).isVisible(), true)
  assert.equal(await page.getByRole('button', { name: /Settings/i }).isVisible(), true)
  await page.reload()
  assert.equal(await page.locator('.canvas-tool-rail').count(), 1)
  assert.equal(await page.locator('.project-board-strip').count(), 1)
  console.log('Responsive workspace checks passed at 1920, 1100 and 800 px')
} finally {
  await browser.close()
}
