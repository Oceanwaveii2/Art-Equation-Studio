/** No serialization or temporary strings. Immutable shared branches stop the
 * comparison immediately. Models here are acyclic JSON records, not DOM/media. */
export function modelEqual(a: unknown, b: unknown): boolean {
  if (Object.is(a, b)) return true
  if (!a || !b || typeof a !== 'object' || typeof b !== 'object') return false
  if (Array.isArray(a) !== Array.isArray(b)) return false
  const left = a as Record<string, unknown>, right = b as Record<string, unknown>
  const keys = Object.keys(left)
  return keys.length === Object.keys(right).length && keys.every(key => Object.hasOwn(right, key) && modelEqual(left[key], right[key]))
}
